/**
 * OLED初始化
 */
void OLED_Init(){
    GPIO_InitTypeDef GPIO_InitStructure;
    I2C_InitTypeDef  I2C_InitStructure;

    /* 1. 开时钟：I2C1 挂在 APB1，GPIOB 挂在 APB2 */
    RCC_APB1PeriphClockCmd(RCC_APB1Periph_I2C1, ENABLE);
    RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOB, ENABLE);

    /* 2. PB6-SCL / PB7-SDA：复用开漏输出 */
    GPIO_InitStructure.GPIO_Pin   = GPIO_Pin_6 | GPIO_Pin_7;
    GPIO_InitStructure.GPIO_Mode  = GPIO_Mode_AF_OD;
    GPIO_InitStructure.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_Init(GPIOB, &GPIO_InitStructure);

    /* 3. I2C 参数 */
    I2C_InitStructure.I2C_Mode                = I2C_Mode_I2C;
    I2C_InitStructure.I2C_DutyCycle           = I2C_DutyCycle_2;      /* 标准模式任意，快速模式用 Tlow/Thigh=2 */
    I2C_InitStructure.I2C_OwnAddress1         = 0x00;                 /* 主机模式随便填 */
    I2C_InitStructure.I2C_Ack                 = I2C_Ack_Enable;
    I2C_InitStructure.I2C_AcknowledgedAddress = I2C_AcknowledgedAddress_7bit;
    I2C_InitStructure.I2C_ClockSpeed          = 400000;           /* 100000 或 400000 */
    I2C_Init(I2C1, &I2C_InitStructure);

    I2C_Cmd(I2C1, ENABLE);
    OLED_PanelInit();
}

uint8_t wait_flag(uint32_t flag, FlagStatus st)
{
    uint32_t t = I2C1_TIMEOUT;
    while (I2C_GetFlagStatus(I2C1, flag) != st) {
        if (--t == 0) return 1;   /* 超时 */
    }
    return 0;
}

uint8_t wait_event(uint32_t evt)
{
    uint32_t t = I2C1_TIMEOUT;
    while (!I2C_CheckEvent(I2C1, evt)) {
        if (--t == 0) return 1;
    }
    return 0;
}

/* 写一个寄存器字节：devAddr 为 7 位地址(不含读写位) */
uint8_t I2C1_WriteReg(uint8_t devAddr, uint8_t reg, uint8_t data)
{
    if (wait_flag(I2C_FLAG_BUSY, RESET)) return 1;

    I2C_GenerateSTART(I2C1, ENABLE);
    if (wait_event(I2C_EVENT_MASTER_MODE_SELECT)) return 2;

    I2C_Send7bitAddress(I2C1, devAddr << 1, I2C_Direction_Transmitter);
    if (wait_event(I2C_EVENT_MASTER_TRANSMITTER_MODE_SELECTED)) return 3;

    I2C_SendData(I2C1, reg);
    if (wait_event(I2C_EVENT_MASTER_BYTE_TRANSMITTING)) return 4;

    I2C_SendData(I2C1, data);
    if (wait_event(I2C_EVENT_MASTER_BYTE_TRANSMITTED)) return 5;

    I2C_GenerateSTOP(I2C1, ENABLE);
    return 0;
}

/* 读一个寄存器字节 */
uint8_t I2C1_ReadReg(uint8_t devAddr, uint8_t reg, uint8_t *buf)
{
    if (wait_flag(I2C_FLAG_BUSY, RESET)) return 1;

    /* 写寄存器地址 */
    I2C_GenerateSTART(I2C1, ENABLE);
    if (wait_event(I2C_EVENT_MASTER_MODE_SELECT)) return 2;

    I2C_Send7bitAddress(I2C1, devAddr << 1, I2C_Direction_Transmitter);
    if (wait_event(I2C_EVENT_MASTER_TRANSMITTER_MODE_SELECTED)) return 3;

    I2C_SendData(I2C1, reg);
    if (wait_event(I2C_EVENT_MASTER_BYTE_TRANSMITTED)) return 4;

    /* 重启起始 + 读 */
    I2C_GenerateSTART(I2C1, ENABLE);
    if (wait_event(I2C_EVENT_MASTER_MODE_SELECT)) return 5;

    I2C_AcknowledgeConfig(I2C1, DISABLE);          /* 单字节读，收到后 NACK */
    I2C_Send7bitAddress(I2C1, (devAddr << 1) | 1, I2C_Direction_Receiver);
    if (wait_event(I2C_EVENT_MASTER_RECEIVER_MODE_SELECTED)) return 6;

    I2C_GenerateSTOP(I2C1, ENABLE);
    if (wait_flag(I2C_FLAG_RXNE, RESET)) return 7;

    *buf = I2C_ReceiveData(I2C1);
    I2C_AcknowledgeConfig(I2C1, ENABLE);
    return 0;
}


static uint8_t OLED_Cmd(uint8_t c){
    return I2C1_WriteReg(0x3C,0x00,c);
}
static uint8_t OLED_Data(uint8_t d){
    return I2C1_WriteReg(0x3C,0x40,d);
}

static void OLED_PanelInit(void){
    OLED_Cmd(0xAE);                    /* 先关显示 */
    OLED_Cmd(0xD5); OLED_Cmd(0x80);    /* 时钟分频 */
    OLED_Cmd(0xA8); OLED_Cmd(0x3F);    /* 多路复用 64 行 */
    OLED_Cmd(0xD3); OLED_Cmd(0x00);    /* 显示偏移 0 */
    OLED_Cmd(0x40);                    /* 起始行 0 */
    OLED_Cmd(0x8D); OLED_Cmd(0x14);    /* ★ 开电荷泵（关键） */
    OLED_Cmd(0x20); OLED_Cmd(0x00);    /* 水平寻址模式 */
    OLED_Cmd(0xA1);                    /* 段重映射 */
    OLED_Cmd(0xC8);                    /* COM 扫描方向 */
    OLED_Cmd(0xDA); OLED_Cmd(0x12);    /* COM 引脚配置 */
    OLED_Cmd(0x81); OLED_Cmd(0xCF);    /* 对比度 */
    OLED_Cmd(0xD9); OLED_Cmd(0xF1);    /* 预充电 */
    OLED_Cmd(0xDB); OLED_Cmd(0x40);    /* VCOMH */
    OLED_Cmd(0xA4);                    /* 恢复正常显示（撤销整屏强制） */
    OLED_Cmd(0xAF);                    /* 显示开 */
}

void OLED_Test(void){
    OLED_Cmd(0x21);OLED_Cmd(0x00);OLED_Cmd(0x7F);
    OLED_Cmd(0x22);OLED_Cmd(0x00);OLED_Cmd(0x0F);
    for(int i=0;i<128*8;i++){
        OLED_Data(image[i]);
    }
}

void OLED_Display(void){
    OLED_Cmd(0x21);OLED_Cmd(0x00);OLED_Cmd(0x7F);
    OLED_Cmd(0x22);OLED_Cmd(0x00);OLED_Cmd(0x0F);
    for(int i=0;i<8;i++){
        for(int j=0;j<128;j++){
            OLED_Data(0xFF);
        }
    }
    for(int i=0;i<8;i++){
        for(int j=0;j<128;j++){
            OLED_Data(disbuf[i][j]);
        }
    }
    OLED_Cmd(0x20); OLED_Cmd(0x02);    /* 页寻址模式 */
}


void draw_pixel(int x,int y,int color){
    x = x - 1;
    y = y - 1;
    if(x > WIDTH || y > HEIGHT || x < 0 || y < 0) return;
    int page = y / 8;
    int bitx = y % 8;

    uint8_t b = disbuf[page][x];
    if(color) b |= (1 << bitx);
    else b &= ~(1 << bitx);
    disbuf[page][x] = b;

    //选中指定的page
    OLED_Cmd(0xB0|page);
    //选中指定的col
    OLED_Cmd(0x00|(x&0x0F));        //低四位地址
    OLED_Cmd(0x10|((x>>4)&0x0F));   //高四位地址

    OLED_Data(b);
}

void fill_rect(int x,int y,int w,int h,int color){
    w = (w + x < WIDTH ? w+x : WIDTH);
    h = (h + y < HEIGHT ? h+y : HEIGHT);

    for(int i=x;i<w;i++){
        for(int j=y;j<h;j++){
            draw_pixel(i,j,color);
        }
    }
}